// BITCOIN UP OR DOWN'S MANIFEST VERSION 26, SIGNED BY ITS DEVELOPER: version 25 in every term, with the new client
// client/index-v26.html (a locked order says when the window closes, no cancel past an order's expiry, no Buy in a window not ready;
// bitcoin-arena kanban #3079, #3080, #3075) beside version 25's. Parent: version 25.
//
//   node tools/sign-manifest-v26.mjs <dev dir holding game-dev.pkcs8>
//
// Writes only public bytes: plugin/btc-updown-v26.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V25, GAME_ID_V25 } from '../plugin/btc-updown-v25.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';
import { UPDOWN_CLIENT_V26_HASH } from '../plugin/market-terms.js';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v26.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V25.gameDevPubkey)) throw new Error(`that key is not Up/Down's developer key ${toHex(MANIFEST_V25.gameDevPubkey).slice(0, 16)}`);
const v26 = new Uint8Array(UPDOWN_CLIENT_V26_HASH);
const { signature, ...v25body } = MANIFEST_V25;
void signature;
const body = { ...v25body, version: MANIFEST_V25.version + 1, parentManifestId: GAME_ID_V25,
  clients: [...MANIFEST_V25.clients.map((c) => new Uint8Array(c)), v26].sort((x, y) => Buffer.compare(Buffer.from(x), Buffer.from(y))) };
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V25) ? MANIFEST_V25 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/btc-updown-v26.js', import.meta.url), `// GENERATED by tools/sign-manifest-v26.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// btc-updown-15m's GameManifest version 26: version 25 (${toHex(GAME_ID_V25)}) in every term, with the new client
// ${toHex(v26)} (the window's close named, no cancel past expiry, no Buy before the window is ready) beside version 25's; requires protocol version ${body.requiredProtocolVersion}.
// Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it and never signs.
// game_id ${id}
import { GAME as V1 } from './btc-updown.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V26_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V26 = decodeManifest(fromHex(MANIFEST_V26_HEX));
export const GAME_ID_V26 = gameIdOf(MANIFEST_V26);
/** What a launcher loads from this module (ARENA_APPS): the registration. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V26, gameId: GAME_ID_V26 });
`);
console.log(`btc-updown-15m v${body.version}: parent ${toHex(GAME_ID_V25).slice(0, 16)}, clients ${body.clients.map((c) => toHex(c).slice(0, 8)).join(' ')}, game_id ${id}`);
